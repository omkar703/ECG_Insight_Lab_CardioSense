"""Typed schemas and data models for CardioSense Explain Results service."""

from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional


class WorkflowType(str, Enum):
    """Supported workflows for AI-generated result explanations."""
    WORKFLOW_A_DIGITIZATION = "workflow_a_digitization"
    WORKFLOW_B_12LEAD = "workflow_b_12lead"
    WORKFLOW_C_SINGLE_LEAD = "workflow_c_single_lead"
    HARDWARE_SIMULATION = "hardware_simulation"


@dataclass
class ExplanationPayload:
    """Sanitized, whitelist-filtered payload passed to Groq for explanation.

    Strict Privacy Guarantee:
        Never contains raw ECG waveforms, image arrays, patient identifiers,
        local filesystem paths, machine names, or environment secrets.
    """
    workflow: str
    source_category: str
    is_simulation: bool
    units_and_calibration: str
    summary_metrics: Dict[str, Any]
    data_quality_flags: List[str]
    known_limitations: List[str]
    sampling_rate_hz: Optional[float] = None
    class_predictions: Optional[List[Dict[str, Any]]] = None
    evaluation_context: Optional[Dict[str, Any]] = None
    schema_version: str = "1.0"

    def to_dict(self) -> Dict[str, Any]:
        """Convert payload to a clean dictionary for JSON serialization."""
        return {
            "schema_version": self.schema_version,
            "workflow": self.workflow,
            "source_category": self.source_category,
            "is_simulation": self.is_simulation,
            "sampling_rate_hz": self.sampling_rate_hz,
            "units_and_calibration": self.units_and_calibration,
            "summary_metrics": self.summary_metrics,
            "class_predictions": self.class_predictions or [],
            "data_quality_flags": self.data_quality_flags,
            "evaluation_context": self.evaluation_context or {},
            "known_limitations": self.known_limitations,
        }


@dataclass
class ExplanationResult:
    """Structured, plain-language explanation generated by Groq."""
    success: bool
    workflow: str
    model_id: str
    simple_terms: str
    what_numbers_mean: str
    what_stands_out: str
    limitations: str
    what_this_does_not_tell_you: str
    suggested_next_step: str
    cached: bool = False
    error_message: Optional[str] = None
    raw_response: Optional[Dict[str, Any]] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
